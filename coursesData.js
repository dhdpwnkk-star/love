/**
 * AI Course Selector with smart rotation and variation
 */
let _courseRotationHistory = {};

function getAICourseRecommendation(location, mood, budget) {
  const locKey = AI_COURSE_ENGINE[location] ? location : '성수';
  const locData = AI_COURSE_ENGINE[locKey];

  const moodKey = (locData && locData[mood]) ? mood : 'romantic';
  const moodData = locData[moodKey];

  let targetTier = budget;
  if (!targetTier || targetTier === 'all') {
    const availableTiers = ['budget', 'standard', 'luxury'];
    targetTier = availableTiers[Math.floor(Math.random() * availableTiers.length)];
  }

  const courseList = moodData[targetTier] || moodData['standard'] || moodData['budget'] || [];
  if (!courseList || courseList.length === 0) {
    return null;
  }

  const historyKey = `${locKey}_${moodKey}_${targetTier}`;
  const nextIndex = ((_courseRotationHistory[historyKey] || 0)) % courseList.length;
  _courseRotationHistory[historyKey] = nextIndex + 1;

  const selected = courseList[nextIndex];
  return {
    ...selected,
    locationKey: locKey,
    locationName: locData.name,
    moodKey: moodKey,
    budgetTier: targetTier
  };
}

